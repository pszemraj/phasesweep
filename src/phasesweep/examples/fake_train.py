"""Toy training script used by phasesweep examples and tests.

The loss is a deterministic formula of the model, optimizer and regularization values. An
optional integer ``seed`` (a top-level ``seed`` in the config YAML, or a ``seed=N`` /
``--seed=N`` token) adds a Gaussian term of scale ``SEED_NOISE_SCALE``, drawn deterministically
from that seed and the trial's hyperparameters, so one seed gives different configurations
different noise: neighboring learning rates scatter around the trend, and repeats over seeds
spread, the way a noisy objective does. Without a seed there is no noise.
"""

from __future__ import annotations

import argparse
import math
import random
import time
from pathlib import Path
from typing import Any

import yaml

from phasesweep import report_objective
from phasesweep.runtime.json import JsonObject, JsonValue

#: Standard deviation of the loss noise a ``seed`` adds, comparable to the loss gap between
#: neighboring learning rates.
SEED_NOISE_SCALE = 0.02


def _parse_kv(tokens: list[str]) -> dict[str, Any]:
    """Parse the toy trainer's supported argparse/Hydra override tokens.

    :param list[str] tokens: Remaining ``key=value`` or ``--key=value`` tokens.
    :raises ValueError: A token or key is unsupported by this trainer.
    :return dict[str, Any]: Parsed numeric values keyed by trainer config path.
    """
    integer_keys = {"n_layers", "model.n_layers", "seed"}
    float_keys = {
        "lr",
        "optimizer.lr",
        "weight_decay",
        "optimizer.weight_decay",
        "dropout",
        "model.dropout",
    }
    overrides: dict[str, Any] = {}
    for raw_token in tokens:
        token = raw_token[2:] if raw_token.startswith("--") else raw_token
        if "=" not in token:
            raise ValueError(f"Unsupported trainer argument {raw_token!r}; expected key=value.")
        key, raw_value = token.split("=", 1)
        if key not in integer_keys | float_keys:
            raise ValueError(f"Unsupported fake-trainer override {key!r}.")
        try:
            value = int(raw_value) if key in integer_keys else float(raw_value)
        except ValueError as exc:
            raise ValueError(
                f"Fake-trainer override {key!r} must be numeric, got {raw_value!r}."
            ) from exc
        overrides[key] = value
    return overrides


def _load_config(path: Path) -> dict[str, Any]:
    """Load the complete YAML config supplied by PhaseSweep.

    :param Path path: Generated per-trial trainer config path.
    :raises ValueError: The YAML root is not a mapping.
    :return dict[str, Any]: Parsed trainer configuration.
    """
    loaded = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(loaded, dict):
        raise ValueError(f"Trainer config {path} must contain a mapping at its top level.")
    return loaded


def _get(config: JsonObject, path: str, default: JsonValue) -> JsonValue:
    """Read one dotted path from a nested trainer config.

    :param JsonObject config: Parsed trainer configuration.
    :param str path: Dotted mapping path.
    :param JsonValue default: Value returned when the path is absent.
    :return JsonValue: Resolved value or ``default``.
    """
    current: JsonValue = config
    for part in path.split("."):
        if not isinstance(current, dict) or part not in current:
            return default
        current = current[part]
    return current


def _scalar(value: JsonValue) -> str | int | float:
    """Require a config value that a numeric constructor accepts.

    :param JsonValue value: Value read from the trainer config.
    :raises ValueError: The value is null, a list, or a mapping.
    :return str | int | float: The value, unchanged.
    """
    if value is None or isinstance(value, (list, dict)):
        raise ValueError(f"Trainer config value {value!r} must be a number.")
    return value


def main() -> None:
    """Run the toy trainer end-to-end: parse args, compute metrics, write result.json."""
    p = argparse.ArgumentParser()
    p.add_argument(
        "--config",
        dest="config_path",
        help="Complete trainer YAML generated by PhaseSweep (primary interface).",
    )
    p.add_argument("--n_layers", type=int)
    p.add_argument("--lr", type=float)
    p.add_argument("--weight_decay", type=float)
    p.add_argument("--dropout", type=float)
    p.add_argument(
        "--sleep",
        type=float,
        default=None,
        help="seconds to sleep before writing result (simulates a long trial; used by tests)",
    )
    args, remaining = p.parse_known_args()

    config: dict[str, Any] = {}
    if args.config_path is not None:
        config = _load_config(Path(args.config_path))

    overrides: dict[str, Any] = {
        "n_layers": args.n_layers,
        "lr": args.lr,
        "weight_decay": args.weight_decay,
        "dropout": args.dropout,
    }
    overrides = {k: v for k, v in overrides.items() if v is not None}
    overrides.update(_parse_kv(remaining))
    sleep_seconds = float(
        args.sleep if args.sleep is not None else _scalar(_get(config, "runtime.sleep", 0.0))
    )
    if sleep_seconds > 0:
        time.sleep(sleep_seconds)

    n_layers = int(
        overrides.get(
            "model.n_layers",
            overrides.get("n_layers", _scalar(_get(config, "model.n_layers", 8))),
        )
    )
    lr = float(
        overrides.get(
            "optimizer.lr", overrides.get("lr", _scalar(_get(config, "optimizer.lr", 3e-4)))
        )
    )
    weight_decay = float(
        overrides.get(
            "optimizer.weight_decay",
            overrides.get("weight_decay", _scalar(_get(config, "optimizer.weight_decay", 0.05))),
        )
    )
    dropout = float(
        overrides.get(
            "model.dropout", overrides.get("dropout", _scalar(_get(config, "model.dropout", 0.1)))
        )
    )

    loss = (
        0.05 * (n_layers - 8) ** 2
        + 0.5 * (math.log10(max(lr, 1e-12)) - math.log10(3e-4)) ** 2
        + 2.0 * (weight_decay - 0.05) ** 2
        + 1.5 * (dropout - 0.10) ** 2
        + 0.30
    )
    seed = overrides.get("seed", _get(config, "seed", None))
    if seed is not None:
        noise = random.Random(f"{int(seed)}/{n_layers}/{lr!r}/{weight_decay!r}/{dropout!r}")
        loss += noise.gauss(0.0, SEED_NOISE_SCALE)

    param_bytes = n_layers * 1_100_000

    report_objective(
        loss,
        name="eval_loss",
        split="validation",
        policy="synthetic",
        checkpoint="toy_formula",
        step=100,
        extra={
            "param_bytes": param_bytes,
            "config": {
                "n_layers": n_layers,
                "lr": lr,
                "weight_decay": weight_decay,
                "dropout": dropout,
            },
        },
    )

    print(f"step=100 eval_loss={loss:.6f}")
    print(f"final param_bytes={param_bytes}")


if __name__ == "__main__":
    main()
